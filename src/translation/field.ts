import type { CheckboxField } from 'payload'

/**
 * Locales where the "translate to other languages" switch defaults to on.
 * Chinese is the source language; translations are generated from it.
 */
export const DEFAULT_AUTO_TRANSLATE_LOCALES = ['zh']

export type AutoTranslateFieldOptions = {
  name?: string
  label?: string
  description?: string
  defaultCheckedLocales?: string[]
}

export const autoTranslateField = ({
  name = 'autoTranslate',
  label = '翻译为其它语言',
  description = '保存时把当前语言的内容翻译成其它语言',
  defaultCheckedLocales = DEFAULT_AUTO_TRANSLATE_LOCALES,
}: AutoTranslateFieldOptions = {}): CheckboxField => ({
  name,
  label,
  type: 'checkbox',
  localized: true,
  defaultValue: ({ locale }) => (locale ? defaultCheckedLocales.includes(locale) : false),
  admin: {
    position: 'sidebar',
    description,
  },
})

export type AiTranslatedFieldOptions = {
  name?: string
  label?: string
  description?: string
}

/**
 * Localized switch that marks a locale's content as generated by AI.
 * The translation task turns it on whenever it writes a locale.
 */
export const aiTranslatedField = ({
  name = 'aiTranslated',
  label = '由 AI 翻译',
  description = '该语言的内容由 AI 翻译生成',
}: AiTranslatedFieldOptions = {}): CheckboxField => ({
  name,
  label,
  type: 'checkbox',
  localized: true,
  defaultValue: false,
  admin: {
    position: 'sidebar',
    readOnly: true,
    description,
  },
})
